# ---------------------------------------------------------------- tests


def emit_formula_test(
    a: FormulaAnalysis,
    input_values: dict[str, float],
    expected: float,
    sanity_target: float | None,
) -> str:
    f = a.formula
    node = formula_node_name(f.id)
    fn = snake(node)
    input_msg = input_message_name(f.id) if a.inputs else "Empty"
    kwargs = ", ".join(f"{s}={input_values[s]!r}" for s in a.inputs)
    lines = [
        "# Generated numeric regression tests — the migration-fidelity gate.",
        "# `transcription` pins the node body to the spec expression at generation-time",
        "# reference values; `physics_sanity` (where present) checks the computed value",
        "# against the measured catalog constant (loose: loop corrections are real).",
        (
            f"from gen.messages_pb2 import {input_msg}"
            if a.inputs
            else f"from {TYPES_BINDINGS} import Empty"
        ),
        f"from nodes.{fn} import {fn}",
        "",
        "",
        f"def test_{fn}_transcription():",
        f"    result = {fn}(None, {input_msg}({kwargs}))",
        f"    assert result.formula_id == {_pystr(f.id)}",
        f"    assert result.computes == {_pystr(a.computes)}",
        f"    assert result.tier == {_pystr(f.tier)}",
    ]
    if expected == 0:
        lines.append("    assert abs(result.value) < 1e-12")
    else:
        lines += [
            f"    expected = {expected!r}",
            "    assert abs(result.value / expected - 1.0) < 1e-9",
        ]
    if sanity_target is not None and sanity_target != 0:
        lines += [
            "",
            "",
            f"def test_{fn}_physics_sanity():",
            f"    result = {fn}(None, {input_msg}({kwargs}))",
            f"    catalog_value = {sanity_target!r}  # measured, natural units",
            "    assert abs(result.value / catalog_value - 1.0) < 0.25",
        ]
    lines.append("")
    return "\n".join(lines)


